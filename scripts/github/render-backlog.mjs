// Writes docs/agile/backlog.md from backlog.mjs, so the plan reads as a document
// and is reviewed in a pull request before seed-backlog.mjs creates the issues.
// Usage: node scripts/github/render-backlog.mjs
import { writeFileSync } from 'node:fs';

import { EPICS, RETIRED, SPRINTS } from './backlog.mjs';
import { sprintDates, sprintTitle } from './sprints.mjs';

const PRIORITY = { must: 'Must', should: 'Should', could: 'Could' };
const stories = EPICS.flatMap((epic) => epic.stories.map((story) => ({ ...story, epic })));

/** Writes consecutive keys as a range ("C-1 to C-8"), so the retired list stays readable. */
function keyRanges(keys) {
  const runs = [];
  for (const key of keys) {
    const [letter, digits] = key.split('-');
    const number = Number(digits);
    const last = runs.at(-1);
    if (last?.letter === letter && last.to + 1 === number) last.to = number;
    else runs.push({ letter, from: number, to: number });
  }
  const parts = runs.map(({ letter, from, to }) =>
    from === to
      ? `${letter}-${String(from)}`
      : `${letter}-${String(from)} to ${letter}-${String(to)}`,
  );
  return parts.length > 1 ? `${parts.slice(0, -1).join(', ')} and ${parts.at(-1)}` : parts[0];
}

const lines = [
  '# Product backlog',
  '',
  '<!-- Generated by scripts/github/render-backlog.mjs from scripts/github/backlog.mjs. Edit the data, not this file. -->',
  '',
  `${String(EPICS.length)} epics and ${String(stories.length)} stories, ${String(stories.reduce((sum, story) => sum + story.points, 0))} story points in all. Each story becomes a GitHub issue under its epic, in the milestone of its sprint (\`node scripts/github/seed-backlog.mjs\`). Stories marked done were delivered by the branch named beside them; the seed closes them once that pull request is merged.`,
  '',
  'Estimates use story points (1, 2, 3, 5, 8, 13) and priorities use MoSCoW. Owners pick up the stories of their area at sprint planning ([working agreement](working-agreement.md)); [module-ownership.md](../team/module-ownership.md) names the owner of each area.',
  '',
  `The stories marked done built the platform that carries over to statement #5. The stories that served only an earlier problem statement were dropped by [ADR 0023](../${RETIRED.decision.replace(/^docs\//, '')}): ${keyRanges(RETIRED.keys)}. Keys are never reused, their issues are closed, and the stories stay in the archive tag the ADR names.`,
  '',
  '## Sprints',
  '',
  '| Sprint | Dates | Goal | Stories | Points |',
  '| ------ | ----- | ---- | ------- | ------ |',
];

for (const sprint of SPRINTS) {
  const inSprint = stories.filter((story) => story.sprint === sprint.number);
  const { label } = sprintDates(sprint.number);
  lines.push(
    `| ${String(sprint.number)} | ${label} | ${sprint.goal} | ${inSprint.map((story) => story.key).join(', ') || '—'} | ${String(inSprint.reduce((sum, story) => sum + story.points, 0))} |`,
  );
}

const anchor = (story) =>
  `${story.key}-${story.title}`
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-');

for (const epic of EPICS) {
  lines.push('', `## Epic ${epic.key}: ${epic.title}`, '', epic.goal, '');
  lines.push('| Story | Title | Sprint | Points | Priority | Status |');
  lines.push('| ----- | ----- | ------ | ------ | -------- | ------ |');
  for (const story of epic.stories) {
    lines.push(
      `| [${story.key}](#${anchor(story)}) | ${story.title} | ${String(story.sprint)} | ${String(story.points)} | ${PRIORITY[story.priority]} | ${story.done ? `Done (\`${story.deliveredBy}\`)` : 'Planned'} |`,
    );
  }
  for (const story of epic.stories) {
    lines.push(
      '',
      `### ${story.key}: ${story.title}`,
      '',
      story.story,
      '',
      '**Acceptance criteria**',
      '',
    );
    for (const criterion of story.acceptance) lines.push(`- ${criterion}`);
  }
}

writeFileSync(new URL('../../docs/agile/backlog.md', import.meta.url), `${lines.join('\n')}\n`);
console.log(
  `wrote docs/agile/backlog.md: ${String(EPICS.length)} epics, ${String(stories.length)} stories`,
);

// The wiki's sprint calendar comes from the same data, so the two never disagree.
const calendar = [
  '# Sprint calendar',
  '',
  '<!-- Generated by scripts/github/render-backlog.mjs. Edit scripts/github/backlog.mjs, not this page. -->',
  '',
  'One sprint per module week, Monday to Sunday, from W1 on 19 October 2026. Each sprint is a milestone and an iteration on the **HuiTong delivery** board. The dates assume no term break; if the academic calendar has one, the sprints after it move.',
  '',
  '| Sprint | Dates | Goal |',
  '| ------ | ----- | ---- |',
  ...SPRINTS.map(
    (sprint) =>
      `| ${sprintTitle(sprint.number)} | ${sprintDates(sprint.number).label} | ${sprint.goal} |`,
  ),
  '',
  'The stories planned for each sprint are in the [backlog](https://github.com/xiu2809xiu-rgb/sccci-innovation-project/blob/main/docs/agile/backlog.md#sprints).',
];
writeFileSync(
  new URL('../../docs/wiki/Sprint-Calendar.md', import.meta.url),
  `${calendar.join('\n')}\n`,
);
console.log('wrote docs/wiki/Sprint-Calendar.md');
